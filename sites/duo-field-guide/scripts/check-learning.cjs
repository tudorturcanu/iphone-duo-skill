'use strict';
const assert = require('node:assert/strict');
const { Progress } = require('../dist/learning-progress.js');
const p = new Progress();
for (const id of ['meet', 'resize', 'regions', 'bars', 'state', 'build']) p.visit(id);
assert.deepEqual(p.completed(), [], 'Navigation alone must not complete exercises.');
for (const pose of ['open', 'book', 'portrait']) p.record('meet', { type: 'pose', pose });
assert.ok(p.isComplete('meet'));
p.record('resize', {type:'layout',width:900,fragile:false});
assert.equal(p.steps.resize.size,0,'Starting wide is not the expand-after-collapse exercise.');
p.record('resize', {type:'layout',width:320,fragile:true});
p.record('resize', {type:'layout',width:320,fragile:false});
p.record('resize', {type:'layout',width:900,fragile:false});
assert.ok(p.isComplete('resize'));
p.record('state', {type:'draft',note:'one',text:'Private sample text'});
p.record('state', {type:'pose',pose:'open',note:'one',text:'Private sample text'});
assert.equal(p.isComplete('state'),false,'Reopening must follow closing.');
p.record('state', {type:'pose',pose:'outer',note:'two',text:'Different text'});
assert.equal(p.steps.state.has('closed'),false,'A different selected draft must not pass continuity.');
p.record('state', {type:'pose',pose:'outer',note:'one',text:'Private sample text'});
assert.equal(JSON.stringify(p.snapshot()).includes('Private'),false,'Draft content must never be serialized.');
assert.equal(new Progress(p.snapshot()).steps.state.size,0,'Partial continuity needs a fresh draft after reload.');
p.record('state', {type:'pose',pose:'open',note:'one',text:'Private sample text'});
assert.ok(p.isComplete('state'));
assert.ok(new Progress(p.snapshot()).isComplete('state'),'Completed milestones survive reload without a draft.');
p.record('build', {type:'quiz',correctCount:3});
assert.equal(p.isComplete('build'),false,'The SDK comparison is part of the build exercise.');
p.record('build', {type:'sdk',sdk:'26'});p.record('build',{type:'sdk',sdk:'27.1'});
assert.ok(p.isComplete('build'));
const invalid=new Progress({version:2,lastChapter:'__proto__',steps:{meet:['open','unknown','book'],state:['edited']}});
assert.equal(invalid.lastChapter,'meet');assert.equal(invalid.steps.meet.size,2);assert.equal(invalid.steps.state.size,0);
console.log('PASS: navigation, exercise milestones, draft continuity, persistence, and storage privacy.');
